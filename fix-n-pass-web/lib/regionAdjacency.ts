const LABEL_SET = new Set(ALL_REGION_LABELS);

function addEdge(m: Map<string, Set<string>>, a: string, b: string) {
  if (!LABEL_SET.has(a) || !LABEL_SET.has(b) || a === b) return;
  if (!m.has(a)) m.set(a, new Set());
  if (!m.has(b)) m.set(b, new Set());
  m.get(a)!.add(b);
  m.get(b)!.add(a);
}

