/** 주소 문자열에서 선택 가능 라벨 하나를 찾는다 (긴 라벨 우선 부분일치). */
export function matchRegionFromAddress(address: string): string | null {
  const t = (address || "").trim();
  if (!t) return null;
  const sorted = [...ALL_REGION_LABELS].sort((a, b) => b.length - a.length);
  for (const r of sorted) {
    if (t.includes(r)) return r;
  }
  const parts = t.split(/\s+/).filter(Boolean);
  if (parts.length >= 2) {
    const sido = SIDO_ALIASES[parts[0]] || parts[0];
    const cand = `${sido} ${parts[1]}`;
    if (LABEL_SET.has(cand)) return cand;
  }
  return null;
}

/** 소재지 기준: 해당 구·시 + 행정경계가 맞닿는 인접 지역(데이터에 정의된 범위). */
export function getDefaultInterestRegions(address: string): string[] {
  const r = matchRegionFromAddress(address);
  if (!r) return [];
  const nb = REGION_NEIGHBORS.get(r) || [];
  return [...new Set([r, ...nb])].sort((a, b) => a.localeCompare(b, "ko"));
}
